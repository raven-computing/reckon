#!/bin/bash
# Golden sample: Contains Bash language features and constructs

# =================================================================================================
# Shell options
# =================================================================================================
set -Eeuo pipefail;
shopt -s extglob nullglob globstar lastpipe;
set -o noclobber;
set +o noclobber;

# =================================================================================================
# Aliases
# =================================================================================================
alias ll='ls -alF';
unalias ll 2>/dev/null || true;

# =================================================================================================
# Variable declarations
# =================================================================================================
plain="value";
readonly RO="immutable";
declare -ir INT_RO=7;
declare -x EXPORTED="env";
declare -l LOWER="TOLOWER";
declare -u UPPER="toupper";
declare -i num=10;
declare -a indexed=(a b "c d");
declare -A assoc=([k1]=v1 ["k 2"]="v 2");
declare -n nameref=indexed;

# =================================================================================================
# Parameter expansion
# =================================================================================================
: "${MISSING:=default_assign}";
: "${EXPORTED:-fallback}";
: "${EXPORTED:+alternate}";
: "${EXPORTED:?must be set}";
: "${#EXPORTED}";
: "${EXPORTED:1:3}";
: "${EXPORTED/por/XXX}";
: "${EXPORTED//o/O}";
: "${EXPORTED/#e/E}";
: "${EXPORTED/%d/D}";
: "${EXPORTED%%or*}";
: "${EXPORTED%d}";
: "${EXPORTED##*or}";
: "${EXPORTED#e}";
: "${EXPORTED^}";
: "${EXPORTED^^}";
: "${EXPORTED,}";
: "${EXPORTED,,}";
: "${EXPORTED@Q}";
: "${EXPORTED@a}";
: "${!assoc[@]}";
: "${!assoc[*]}";
: "${#indexed[@]}";
: "${indexed[*]}";
: "${indexed[@]:0:2}";

# =================================================================================================
# Special parameters
# =================================================================================================
set -- "arg1" "arg 2" "arg3";
: "$0" "$#" "$*" "$@" "$?" "$-" "$$" "$!" "${!#}";
: "${PIPESTATUS[*]:-}";
: "${BASH_VERSION}" "${BASH_SOURCE[0]}" "${FUNCNAME[0]:-main}" "${LINENO}";
: "$SECONDS" "$RANDOM" "$EPOCHSECONDS" "$BASHPID";

# =================================================================================================
# Arithmetic
# =================================================================================================
arith=$((INT_RO + num * 2 - 1));
(( num += 5 ));
let "num -= 2";
(( num++, num-- ));
(( num > 0 ? 1 : 0 ));
(( num <<= 1 ));
(( num >>= 1 ));
(( num &= 0xFF ));
(( num |= 1 ));
(( num ^= 3 ));
(( num %= 7 ));
(( num /= 2 )) || true;

# =================================================================================================
# Arrays
# =================================================================================================
indexed+=(e f);
indexed[5]="sparse";
unset 'indexed[5]';
assoc+=([k3]=v3);
unset 'assoc[k3]';
copy=("${indexed[@]}");

# =================================================================================================
# Functions
# =================================================================================================
function fn_keyword() {
  local x="${1:-default}";
  local -i li=0;
  local -a la=();
  local -A lA=();
  local -n ln=$2 2>/dev/null || true;
  [[ -n "$x" ]] && return 0 || return 1;
}

fn_posix() {
  printf '%s\n' "${@}" > /dev/null;
}

fn_recursive() {
  (( $1 <= 1 )) && { echo 1; return; }
  local prev;
  prev=$(fn_recursive $(($1 - 1)));
  echo $(($1 * prev));
}

# =================================================================================================
# Trap
# =================================================================================================
trap 'echo cleanup' EXIT;
trap '' PIPE;
trap - INT TERM;
trap 'echo caught' SIGUSR1;

# =================================================================================================
# Conditionals: if / elif / else
# =================================================================================================
if [[ -n "$plain" && "$plain" =~ ^[[:alpha:]]+$ ]]; then
  :
elif [[ -z "$plain" || "$plain" == "other" ]]; then
  :
elif [ -f /dev/null ]; then
  :
elif [ -d /tmp ] && [ -r /tmp ]; then
  :
elif test -e /dev/null; then
  :
else
  :
fi

# =================================================================================================
# Conditionals: [[ ]] operators
# =================================================================================================
[[ "abc" == a* ]] && :;
[[ "abc" != z* ]] && :;
[[ "abc" < "def" ]] && :;
[[ "abc" > "aaa" ]] && :;
[[ "abc" =~ ^[a-z]+$ ]] && :;
[[ -v plain ]] && :;
[[ -z "" ]] && :;
[[ -n "x" ]] && :;
[[ -f /dev/null ]] && :;
[[ -d /tmp ]] && :;
[[ -r /dev/null ]] && :;
[[ -w /dev/null ]] && :;
[[ -x /bin/sh ]] && :;
[[ -s /dev/null ]] || :;
[[ -L /dev/stdin ]] || :;
[[ -p /dev/stdin ]] || :;
[[ -S /dev/null ]] || :;
[[ -b /dev/null ]] || :;
[[ -c /dev/null ]] && :;
[[ -t 0 ]] || :;
[[ -e /dev/null ]] && :;
[[ /dev/null -nt /dev/null ]] || :;
[[ /dev/null -ot /dev/null ]] || :;
[[ /dev/null -ef /dev/null ]] && :;

# =================================================================================================
# Conditionals: arithmetic (( ))
# =================================================================================================
(( num > 0 )) && : || :;
(( num == 10 || num == 5 )) || :;

# =================================================================================================
# Case statement (all terminators)
# =================================================================================================
case "${1:-x}" in
  a*)   : ;&
  c|d)  : ;;
  *)    : ;;
esac

# =================================================================================================
# Loops: for
# =================================================================================================
for v in "${indexed[@]}"; do
  : "$v";
done

# =================================================================================================
# Loops: C-style for
# =================================================================================================
for ((i = 0; i < 3; i++)); do
  ((i == 1)) && continue;
  :
done

# =================================================================================================
# Loops: while
# =================================================================================================
n=3;
while ((n > 0)); do
  ((n--));
  ((n == 1)) && break;
done

# =================================================================================================
# Loops: until
# =================================================================================================
until false; do
  break;
done

# =================================================================================================
# Loops: infinite
# =================================================================================================
while :; do
  break;
done

# =================================================================================================
# Select
# =================================================================================================
PS3="pick> ";
select choice in alpha beta quit; do
  : "$choice" "$REPLY";
  break;
done < <(echo 1)

# =================================================================================================
# Grouping: brace group
# =================================================================================================
{ printf 'grouped\n'; :; } >/dev/null

# =================================================================================================
# Grouping: subshell
# =================================================================================================
( cd / && pwd >/dev/null )

# =================================================================================================
# Pipelines
# =================================================================================================
echo "abc" | tr a-z A-Z | cat >/dev/null;
echo "abc" |& cat >/dev/null;
! false;

# =================================================================================================
# Lists: && || ; &
# =================================================================================================
true && true || false;
true; false || true;
sleep 0 &
wait $!;

# =================================================================================================
# Time
# =================================================================================================
time { sleep 0; } 2>/dev/null;

# =================================================================================================
# Getopts
# =================================================================================================
parse_getopts() {
  local opt OPTIND=1;
  while getopts ":vn:h" opt; do
    case "$opt" in
      v) : ;;
      n) : "$OPTARG" ;;
      h) : ;;
      :) printf 'missing arg -%s\n' "$OPTARG" >&2 ;;
      \?) printf 'bad opt -%s\n' "$OPTARG" >&2 ;;
    esac
  done
  shift $((OPTIND - 1));
}
parse_getopts -v -n foo;

# =================================================================================================
# Read / mapfile
# =================================================================================================
mapfile -t lines < <(printf 'l1\nl2\n');
readarray -t lines2 < <(printf 'a\nb\n');
while IFS= read -r line; do
  : "$line";
done < <(printf 'x\ny\n')
IFS=, read -r -a csv <<< "a,b,c";
read -r single <<< "word";
read -r -d '' block <<< "multi" || true;
read -r -n 1 -t 0.01 char </dev/null || true;

# =================================================================================================
# Here-document: literal (no expansion)
# =================================================================================================
cat <<'HEREDOC_LITERAL' > /dev/null
literal $text `no expansion` ${none}
HEREDOC_LITERAL

# =================================================================================================
# Here-document: expanding
# =================================================================================================
cat <<HEREDOC_EXPAND >/dev/null
expanded ${EXPORTED} and $plain
HEREDOC_EXPAND

# =================================================================================================
# Here-document: indented (tab-stripped)
# =================================================================================================
cat <<-HEREDOC_INDENT >/dev/null
	indented heredoc
HEREDOC_INDENT

# =================================================================================================
# Here-string
# =================================================================================================
cat <<< "here-string" >/dev/null;

# =================================================================================================
# Command substitution
# =================================================================================================
cs1="$(echo cmd_sub)";
cs2="$(echo nested "$(echo deep)")";
cs3="`echo backtick`";

# =================================================================================================
# Process substitution
# =================================================================================================
diff <(echo a) <(echo b) >/dev/null || true;
echo "proc_sub_out" > >(cat >/dev/null);

# =================================================================================================
# File descriptors / exec / redirection
# =================================================================================================
t="$(mktemp)";

echo "line" > "$t";
echo "append" >> "$t";
cat < "$t" >/dev/null;
cat < "$t" 2>/dev/null 1>/dev/null;
echo "stderr" 2>&1 >/dev/null;
echo "all" &>/dev/null;
echo "all2" >&/dev/null 2>/dev/null || true;

exec 3> "$t";
printf 'fd3\n' >&3;
exec 3>&-;

exec 4< "$t";
read -r _ <&4 || true;
exec 4<&-;

exec {fd_w}> "$t";
printf 'dyn_fd\n' >&"$fd_w";
exec {fd_w}>&-;

exec {fd_r}< "$t";
read -r _ <&"$fd_r" || true;
exec {fd_r}<&-;

rm -f "$t";

# =================================================================================================
# Brace expansion
# =================================================================================================
: {1..5};
: {1..10..2};
: {a..z};
: {A,B,C};
: pre{x,y}post;

# =================================================================================================
# Tilde expansion
# =================================================================================================
: ~ ~+ ~-;

# =================================================================================================
# Globbing / pathname expansion
# =================================================================================================
: /dev/nul?;
: /dev/n*;
: /dev/null;
: /tmp/[a-z]* 2>/dev/null || true;

# =================================================================================================
# Extglob patterns
# =================================================================================================
[[ "foobar" == @(foo|baz)* ]] && :;
[[ "foobar" == ?(foo)bar ]] && :;
[[ "foobar" == *(foo)bar ]] || :;
[[ "foobar" == +(foo)bar ]] || :;
[[ "foobar" != !(foo)* ]] && :;

# =================================================================================================
# Quoting
# =================================================================================================
: 'single quoted';
: "double quoted with $plain";
: $'ansi\tescaped\n';
: $"locale string";
: "escaped \$ and \" and \\";
: "$(echo "nested quotes")";

# =================================================================================================
# Eval
# =================================================================================================
eval 'dyn_var=42';
: "${dyn_var:?must exist}";

# =================================================================================================
# Command / builtin / type / enable / hash
# =================================================================================================
command printf '%s\n' "x" >/dev/null;
command -v printf >/dev/null;
builtin echo "x" >/dev/null;
type -a printf >/dev/null 2>&1 || true;
type -t printf >/dev/null 2>&1 || true;
enable -n test 2>/dev/null || true;
enable test 2>/dev/null || true;
hash -r 2>/dev/null || true;

# =================================================================================================
# Source / dot
# =================================================================================================
source /dev/null;
. /dev/null;

# =================================================================================================
# Coproc
# =================================================================================================
coproc CP { tr '[:lower:]' '[:upper:]'; }
printf 'hi\n' >&"${CP[1]}";
read -r cp_out <&"${CP[0]}";
wait "$CP_PID" 2>/dev/null || true;

# =================================================================================================
# Background / job control
# =================================================================================================
sleep 0 &
bg_pid=$!;
wait "$bg_pid";
jobs >/dev/null 2>&1 || true;
disown 2>/dev/null || true;

# =================================================================================================
# String / array operations
# =================================================================================================
printf -v formatted '%05d' 42;
printf '%s\n' "${indexed[@]}" >/dev/null;
printf '%q\n' "special chars: &|;" >/dev/null;

# =================================================================================================
# Conditional command: && || chains with pipeline
# =================================================================================================
echo ok | grep -q ok && echo matched >/dev/null || echo no >/dev/null;

# =================================================================================================
# Arithmetic for loop with comma operator
# =================================================================================================
for ((x = 0, y = 10; x < 3; x++, y--)); do
  : "$x" "$y";
done

# =================================================================================================
# Nested structures
# =================================================================================================
for a in 1 2; do
  for b in x y; do
    if [[ "$a" == 1 ]]; then
      while true; do
        case "$b" in
          x) break ;;
          *) break ;;
        esac
      done
    fi
  done
done

# =================================================================================================
# Unset / readonly / export / declare post-hoc
# =================================================================================================
unset dyn_var;
unset -v plain;
unset -f fn_posix 2>/dev/null || true;
readonly FINAL_RO="sealed";
export FINAL_EX="exported";
declare -g GLOBAL_VAR="global";

# =================================================================================================
# Misc builtins
# =================================================================================================
: "noop";
true;
false || true;
echo "test" >/dev/null;
printf '%s\n' "test" >/dev/null;
pwd >/dev/null;
cd /tmp && cd - >/dev/null;
pushd /tmp >/dev/null 2>&1;
popd >/dev/null 2>&1;
dirs >/dev/null 2>&1;
umask 0022;
ulimit -n >/dev/null 2>&1 || true;
caller 0 2>/dev/null || true;
getopts "a" opt "" 2>/dev/null || true;
shift 0;
wait;

# =================================================================================================
# String-valued exit
# =================================================================================================
exit 0;
